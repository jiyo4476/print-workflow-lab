-- PRD-13: jobs, their step history, their documents and the properties of both.
-- Written to run unchanged on H2 (PostgreSQL mode, used by the tests) and PostgreSQL.
-- Column names avoid words that are reserved in one of the two (value, position, sequence).

CREATE TABLE jobs (
    id            VARCHAR(64)  PRIMARY KEY,
    state         VARCHAR(32)  NOT NULL,
    phase         VARCHAR(32)  NOT NULL,
    current_step  VARCHAR(255),
    error_message VARCHAR(4000),
    document_count INT         NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX jobs_created_at ON jobs (created_at, id);
CREATE INDEX jobs_state_created_at ON jobs (state, created_at, id);

CREATE TABLE job_properties (
    job_id     VARCHAR(64)  NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    prop_name  VARCHAR(255) NOT NULL,
    prop_value VARCHAR(2000) NOT NULL,
    PRIMARY KEY (job_id, prop_name)
);

CREATE TABLE job_steps (
    job_id        VARCHAR(64)  NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    step_position INT          NOT NULL,
    step_name     VARCHAR(255) NOT NULL,
    phase         VARCHAR(32)  NOT NULL,
    started_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    outcome       VARCHAR(32)  NOT NULL,
    PRIMARY KEY (job_id, step_position)
);

CREATE TABLE documents (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id         VARCHAR(64) NOT NULL REFERENCES jobs (id) ON DELETE CASCADE,
    doc_sequence   INT         NOT NULL,
    input_sequence INT         NOT NULL,
    format         VARCHAR(16),
    queue          VARCHAR(255),
    file_path      VARCHAR(1024)
);
CREATE INDEX documents_job_sequence ON documents (job_id, doc_sequence);
CREATE INDEX documents_queue ON documents (queue);

CREATE TABLE document_properties (
    document_id BIGINT       NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
    prop_name   VARCHAR(255) NOT NULL,
    prop_value  VARCHAR(2000) NOT NULL,
    PRIMARY KEY (document_id, prop_name)
);
CREATE INDEX document_properties_name_value ON document_properties (prop_name, prop_value);
